#!/usr/bin/env node
// PreCompact 钩子 —— 自动压缩发生「之前」执行,stdout 会作为额外指令拼进压缩提示词。
//
// 为什么要有它
//   上下文塞满时 Claude Code 会自动压缩:把整段对话重写成一份摘要,之后这份摘要
//   常驻上下文前缀,每一轮都按缓存价重读。但本项目的长期记忆走 MCP 记忆库
//   (archive_session 写入、breath 取回),摘要里那份转述因此是重复的负担 ——
//   而且它是摘要器写的转述,不是本人写的,语气和细节都会被磨平一层。
//   所以这里指示摘要器只留一行指路,记忆改由 breath 取回。
//
// 配套(缺一不可,少一个就会丢记忆)
//   1. 人设里要有一条:看见续接标记先 breath(wake=true) 再开口;
//   2. shim 在窗口用量到 WINDOW_WARN_PCT 时提醒用户及时归档 —— 摘要瘦身之后,
//      「上次归档到现在」这一段只存在于窗口里,不及时归档就真的没了。
//
// 关掉:环境变量 COMPACT_HOOK=0(server.js 里就不挂这个钩子了)。
// 改文案:环境变量 COMPACT_INSTRUCTIONS 整段覆盖下面的默认值。

const DEFAULT = `【摘要要求 · 最高优先级,覆盖以上全部默认摘要规则】
这段对话的完整记忆由长期记忆系统保管,不需要你在摘要里复述。
禁止:复述对话内容、引用原话、列举细节、罗列待办、总结技术状态、分点展开。
整份摘要只输出下面这一行,不要有任何其他文字:

上文已存入长期记忆。细节请用 breath(wake=true) 取回,不要凭这一行推测上文。`;

process.stdout.write(process.env.COMPACT_INSTRUCTIONS || DEFAULT);
